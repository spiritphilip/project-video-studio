// Generates src/brand.ts from video.config.json (colours, fonts, format, brand copy).
// Usage: node scripts/brand.mjs        (run again whenever the brand block of the config changes)
import fs from 'node:fs';
import path from 'node:path';
import {root, readConfig} from './lib.mjs';

const cfg = readConfig();
const b = cfg.brand;
const fmt = cfg.answers?.format === '9:16' ? {width: 1080, height: 1920} : cfg.answers?.format === '1:1' ? {width: 1080, height: 1080} : {width: 1920, height: 1080};
const mod = (family) => family.replace(/[^A-Za-z0-9]/g, '');
// Fonts: local files (public/fonts, from scripts/fonts.mjs) when every weight is present, else Google Fonts.
const localFile = (f, w) => `fonts/${mod(f.family)}-${w}.woff2`;
const isLocal = (f) => f.weights.every((w) => fs.existsSync(path.join(root, 'public', localFile(f, w))));
const anyLocal = Object.values(b.fonts).some(isLocal);
const font = (key, alias) => {
  const f = b.fonts[key];
  if (isLocal(f)) return `export const ${key.toUpperCase()} = loadLocal(${JSON.stringify(f.family)}, ${JSON.stringify(f.weights.map((w) => [w, localFile(f, w)]))});`;
  return `import {loadFont as load${alias}} from '@remotion/google-fonts/${mod(f.family)}';\nexport const {fontFamily: ${key.toUpperCase()}} = load${alias}('normal', {weights: ${JSON.stringify(f.weights)}, subsets: ['latin']});`;
};
const localLoader = anyLocal ? `import {continueRender, delayRender, staticFile} from 'remotion';

const loadLocal = (family: string, files: [string, string][]) => {
  if (typeof FontFace === 'undefined') return family;
  const handle = delayRender(\`Loading \${family} (local)\`);
  Promise.all(files.map(([weight, file]) => new FontFace(family, \`url(\${staticFile(file)}) format('woff2')\`, {weight}).load().then((face) => document.fonts.add(face))))
    .then(() => continueRender(handle))
    .catch((err) => { console.error(err); continueRender(handle); });
  return family;
};
` : '';

const out = `// GENERATED by scripts/brand.mjs from video.config.json. Do not edit by hand: change the config and run \`npm run brand\`.
${localLoader}${font('head', 'Head')}
${font('display', 'Display')}
${font('body', 'Body')}

export const C = ${JSON.stringify(b.colors, null, 2)} as const;

/** Any brand colour (hex) at a given opacity: alpha(C.primary, 0.4). */
export const alpha = (hex: string, a: number) => {
  if (!hex.startsWith('#')) return hex;
  const h = hex.length === 4 ? hex.slice(1).split('').map((x) => x + x).join('') : hex.slice(1, 7);
  const n = parseInt(h, 16);
  return \`rgba(\${(n >> 16) & 255},\${(n >> 8) & 255},\${n & 255},\${a})\`;
};

export const BRAND = ${JSON.stringify({name: b.name, wordmark: b.wordmark, tagline: b.tagline, pillars: b.pillars, poweredBy: b.poweredBy, logo: b.logo, mark: b.mark, url: (cfg.publish?.site || cfg.project.url || '').replace(/^https?:\/\//, '')}, null, 2)} as const;

export const PRESENTER = ${JSON.stringify(cfg.presenter ?? {}, null, 2)} as const;
export const MUSIC = ${JSON.stringify(cfg.music ?? {default: 'driving-ambition', volume: 0.085})} as const;
export const CAPTIONS = ${JSON.stringify(cfg.answers?.captions ?? 'word-highlight')} as string;
export const BUMPERS = ${JSON.stringify(cfg.answers?.bumpers ?? 'intro-outro')} as 'intro-outro' | 'intro-only' | 'none';
export const TRACKS = ${JSON.stringify(cfg.tracks ?? {}, null, 2)} as Record<string, {name: string; narrator?: string; color?: string}>;

export const FPS = 30;
export const FORMAT = ${JSON.stringify(fmt)} as const;
/** answers.format = "both": every episode is also registered as <id>-Vertical (1080×1920). */
export const ALT_FORMAT = ${cfg.answers?.format === 'both' ? JSON.stringify({width: 1080, height: 1920}) : 'null'} as {width: number; height: number} | null;
export const ms = (v: number) => Math.round((v / 1000) * FPS);
`;
fs.writeFileSync(path.join(root, 'src', 'brand.ts'), out);
console.log('wrote src/brand.ts', fmt.width + 'x' + fmt.height);
